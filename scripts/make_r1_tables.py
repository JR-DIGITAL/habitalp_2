def b3_cd_ablation() -> None:
    rows_ = read("b3_ndsm_gain_9_vs_collapsed.csv")
    if rows_ is None:
        print("skip b3_cd_ablation: b3_ndsm_gain_9_vs_collapsed.csv missing")
        return
    d = {(r["model"], r["postproc"], r["task"]): r for r in rows_}
    blocks = [("change-binary", "9"), ("change-multiclass", "9"), ("change-multiclass", "cc")]
    head = ("& \\multicolumn{4}{c}{Binary CD} & & \\multicolumn{4}{c}{Multi-class CD (9 classes)} & & "
            "\\multicolumn{4}{c}{Multi-class CD, CC collapsed (5)} \\\\\n"
            "\\cmidrule(lr){2-5}\\cmidrule(lr){7-10}\\cmidrule(lr){12-15}\n"
            "Model & RGB+NIR & +nDSM & $\\Delta$ & [95\\% CI] & & RGB+NIR & +nDSM & $\\Delta$ & [95\\% CI] "
            "& & RGB+NIR & +nDSM & $\\Delta$ & [95\\% CI] \\\\")
    body = []
    for pp, title in [("before", "Model output"), ("after", "After post-processing")]:
        body.append(f"\\multicolumn{{15}}{{l}}{{\\textit{{{title}}}}} \\\\")
        sums = defaultdict(list)
        for m in B0_ORDER:
            cells = [NAMES[m]]
            for i, (task, s) in enumerate(blocks):
                r = d[(m, pp, task)]
                e, fv, dl = num(r[f"IoU_E_{s}"]), num(r[f"IoU_F_{s}"]), num(r[f"dIoU_{s}"])
                sums[i].append((fv, e, dl))
                cells += ([""] if i else []) + [f(fv), f(e), fs(dl),
                                                 ci(r[f"dIoU_{s}_ci_low"], r[f"dIoU_{s}_ci_high"])]
            body.append(row(cells))
        cells = ["Mean (6 models)"]
        for i in range(len(blocks)):
            mf, me, md = (sum(v[k] for v in sums[i]) / len(sums[i]) for k in range(3))
            cells += ([""] if i else []) + [f(mf), f(me), fs(md), "-"]
        body += ["\\cmidrule(lr){1-15}", row(cells)]
        if pp == "before":
            body.append("\\midrule")
    cap = ("Effect of adding the LiDAR nDSM on cross-temporal change detection (2013$\\rightarrow$2019/20, "
           "original runs, one per model): macro IoU of RGB+NIR and RGB+NIR+nDSM and $\\Delta$ from "
           "unrounded values, for the model output and after post-processing. CC collapsed: each "
           "CC$<$80 / CC$\\geq$80 distinction removed, so the four canopy-cover change classes merge "
           "into no change or other transition (four change classes plus no change). 95\\% CI of "
           f"$\\Delta$: {CI_TXT} (88 tiles); test-set sampling only, the original runs are single runs.")
    write("b3_cd_ablation",
          table("tab:r1-b3_cd_ablation", cap, "lcccl c cccl c cccl", head, body, size="\\scriptsize",
                sep="2.5pt", wide=True), ["b3_ndsm_gain_9_vs_collapsed.csv"])


