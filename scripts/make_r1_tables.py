def _b1_table(name: str, lo: str, hi: str, cap: str) -> None:
    rows_ = read("b1_paired.csv")
    if rows_ is None:
        print(f"skip {name}: b1_paired.csv missing (B1 pending)")
        return
    pairs, d, fam = [], {}, {}
    for r in rows_:
        a, b = NAMES.get(r["model_a"], r["model_a"]), NAMES.get(r["model_b"], r["model_b"])
        if (a, b) not in pairs:
            pairs.append((a, b))
        d[(a, b, r["metric"])] = r
        fam[(a, b)] = r.get("family") or ("post hoc" if r.get("post_hoc") in ("1", "True") else "main")
    mets = [(m, n) for m, n in B9_METRICS if any(k[2] == m for k in d)]
    header = "Comparison & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{n}}}" for _, n in mets) + " \\\\"
    body, started = [], set()
    blocks = {"cnn": "Against the ResNet-50 U-Net", "supporting": "Supporting comparisons"}
    for a, b in pairs:
        f = fam[(a, b)]
        if f in blocks and f not in started:
            started.add(f)
            body += ["\\midrule", f"\\multicolumn{{{1 + 2 * len(mets)}}}{{l}}{{\\textit{{{blocks[f]}}}}} \\\\"]
        cells = [f"{a} $-$ {b}" + ("$^\\dagger$" if f in ("post hoc", "cnn") else "")]
        for m, _ in mets:
            r = d.get((a, b, m))
            if r is None:
                cells += ["-", ""]
                continue
            lo_v, hi_v = num(r[lo]), num(r[hi])
            if lo_v > 0 or hi_v < 0:  # robust: the CI excludes zero -> bold; keep the sign of a bound that rounds to 0
                bound = lambda v: "$-$0.000" if v < 0 and fs(v) == "0.000" else fs(v)
                cells += [f"\\textbf{{{fs(r['diff'])}}}", f"\\textbf{{[{bound(lo_v)}, {bound(hi_v)}]}}"]
            else:
                cells += [fs(r["diff"]), ci(r[lo], r[hi])]
        body.append(row(cells))
    write(name, table(f"tab:r1-{name}", cap, "l" + "rl" * len(mets), header, body,
                      size="\\scriptsize", sep="3pt", wide=True), ["b1_paired.csv"])


