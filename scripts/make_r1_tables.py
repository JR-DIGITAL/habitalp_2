# ---------------------------------------------------------------- helpers
def read(name: str) -> list[dict] | None:
    p = OUT_CSV / name
    if not p.exists():
        return None
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def num(x) -> float:
    if x is None or x == "":
        return math.nan
    m = re.match(r"\s*[-+]?\d*\.?\d+(e[-+]?\d+)?", str(x), re.I)
    return float(m.group(0)) if m else math.nan


def f(x, d: int = 3) -> str:
    """Plain number, '-' if missing; negatives get a real minus sign."""
    v = num(x)
    if math.isnan(v):
        return "-"
    s = f"{v:.{d}f}"
    if s.startswith("-"):
        return "$-$" + s[1:] if float(s) != 0 else s[1:]
    return s


def fs(x, d: int = 3) -> str:
    """Signed difference (+0.041 / -0.017)."""
    v = num(x)
    if math.isnan(v):
        return "-"
    s = f"{v:+.{d}f}"
    if float(s) == 0:
        return f"{0:.{d}f}"
    return ("$-$" + s[1:]) if s[0] == "-" else s


def ci(lo, hi, d: int = 3, signed: bool = True) -> str:
    g = fs if signed else f
    return f"[{g(lo, d)}, {g(hi, d)}]"


def lr_tex(x) -> str:
    v = num(x)
    if math.isnan(v):
        return "-"
    e = math.floor(math.log10(v) + 1e-9)
    m = v / 10 ** e
    ms = f"{m:.2g}"
    return f"$10^{{{e}}}$" if ms == "1" else f"${ms}\\times10^{{{e}}}$"


def write(name: str, body: str, sources: list[str]) -> None:
    TAB_DIR.mkdir(parents=True, exist_ok=True)
    head = (f"% {name}.tex: generated by scripts/make_r1_tables.py from "
            f"{', '.join('outputs/r1/' + s for s in sources)}.\n"
            "% Do not edit by hand; change the script and rerun.\n")
    text = head + body.strip() + "\n"
    assert "—" not in text and "---" not in text, f"em-dash in {name}"
    (TAB_DIR / f"{name}.tex").write_text(text)
    print(f"wrote {TAB_DIR / name}.tex")


def table(label: str, caption: str, colspec: str, header: str, rows: list[str], *,
          size: str = "\\footnotesize", sep: str = "4pt", wide: bool = False,
          notes: list[str] | None = None) -> str:
    """MDPI table: [H], caption above, booktabs rules; wide = full width via adjustwidth."""
    L = ["\\begin{table}[H]"]
    if wide:
        L.append("\\begin{adjustwidth}{-\\extralength}{0cm}")
    L.append(f"\\caption{{{caption}\\label{{{label}}}}}")
    L += [size, f"\\setlength{{\\tabcolsep}}{{{sep}}}", "\\centering"]
    if notes:
        L.append("\\begin{threeparttable}")
    L += [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header.strip(), "\\midrule"]
    L += rows
    L += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        L += ["\\begin{tablenotes}", "\\scriptsize"] + [f"\\item[{k}] {t}" if k else f"\\item {t}"
                                                      for k, t in notes] + ["\\end{tablenotes}",
                                                                            "\\end{threeparttable}"]
    if wide:
        L.append("\\end{adjustwidth}")
    L.append("\\end{table}")
    return "\n".join(L)


def row(cells: list[str]) -> str:
    return " & ".join(cells) + " \\\\"


