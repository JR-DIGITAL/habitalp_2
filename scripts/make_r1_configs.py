"""Write the training configs of the MDPI revision (round 1) from the Phase E configs.

Usage: python scripts/make_r1_configs.py
Writes src/trainers/terratorch/revision/config-<run name>.yaml. Each config is its Phase E
base config with only the protocol changes of the revision:
masked split (2020 test patches + 128 m buffer kept out of train/val sampling), batch size 4,
200 epochs without early stopping, the cosine schedule stretched to match (T_max 190), a fixed
training seed, W&B tags (the W&B key is kept from the base config). Variants: ResNet-50 U-Net (T4), U-Net decoder checks (T8, T9), TerraMind at
LR 5e-5 (T10) and the two MiT-B2 controls (K1 block-drop split, K2 original split).
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "src" / "trainers" / "terratorch"
OUT = BASE / "revision"

MAX_EPOCHS = 200
WARMUP_EPOCHS = 10
SEEDS = (0, 1, 2)
MASK = {"shape_path": "roi/training_rois_2020.gpkg", "buffer": 128.0, "mode": "mask"}
BLOCK_DROP = {"shape_path": "roi/training_rois_2020.gpkg", "buffer": 0.0, "mode": "drop_cells"}

# three necks that turn ViT tokens into a feature pyramid, as for DOFA and TerraMind
PYRAMID_NECKS = [
    {"name": "SelectIndices"},
    {"name": "ReshapeTokensToImage"},
    {"name": "LearnedInterpolateToPyramidal"},
]
UNET_DECODER = {"decoder": "UNetDecoder", "decoder_channels": [512, 256, 128, 64], "head_dropout": 0.1}


def unet_decoder_args(backbone, bands, indices, **backbone_kwargs):
    necks = copy.deepcopy(PYRAMID_NECKS)
    necks[0]["indices"] = indices
    return {"backbone": backbone, "backbone_pretrained": True, "backbone_bands": bands, **backbone_kwargs,
            "necks": necks, **UNET_DECODER}


# run id -> (base config, model label, seeds, exclusion, overrides)
RUNS = {
    "T1": ("clay-v1", "clay-v1", SEEDS, MASK, {}),
    "T2": ("clay-v1.5", "clay-v1.5", SEEDS, MASK, {}),
    "T3": ("unet-mit-b2", "unet-mit-b2", SEEDS, MASK, {}),
    "T4": ("unet-mit-b2", "unet-resnet50", SEEDS, MASK,
           {"model_args": {"backbone": "resnet50"}, "hyperparameters": {"backbone": "resnet50"}}),
    "T5": ("prithvi-v2-300", "prithvi-v2-300", SEEDS, MASK, {}),
    "T6": ("dofa-base", "dofa-base", SEEDS, MASK, {}),
    "T7": ("terramind", "terramind", SEEDS, MASK, {}),
    # decoder checks: same encoders, U-Net decoder through EncoderDecoderFactory
    "T8": ("clay-v1", "clay-v1-unetdec", (0,), MASK,
           {"model_factory": "EncoderDecoderFactory",
            "model_args": unet_decoder_args("timm_clay_v1_base", ["red", "green", "blue", "nir", "dsm"],
                                            [2, 5, 8, 11], backbone_in_chans=5, backbone_num_frames=1)}),
    "T9": ("prithvi-v2-300", "prithvi-v2-300-unetdec", (0,), MASK,
           {"model_factory": "EncoderDecoderFactory",
            "model_args": unet_decoder_args("prithvi_eo_v2_300", ["RED", "GREEN", "BLUE", "NIR_NARROW", "NDSM"],
                                            [5, 11, 17, 23], backbone_num_frames=1)}),
    "T10": ("terramind", "terramind-lr5e5", (0,), MASK, {"hyperparameters": {"learning_rate": 5e-5}}),
    # controls: reviewer's block-drop split, and the original split under the new protocol
    "K1": ("unet-mit-b2", "unet-mit-b2", SEEDS, BLOCK_DROP, {}),
    "K2": ("unet-mit-b2", "unet-mit-b2", SEEDS, None, {}),
}
SPLIT_LABEL = {"mask": "masked", "drop_cells": "blockdrop", None: "orig"}


def entry(desc, value):
    return {"desc": desc, "value": value}


def make(run_id, base_name, model, seed, exclusion, overrides):
    # Phase E configs; in the public repo they have no phase suffix
    cfg = yaml.safe_load((BASE / f"config-{base_name}-rgb-nir-ndsm.yaml").read_text())
    split = SPLIT_LABEL[exclusion["mode"] if exclusion else None]
    name = f"r1-{model}-{split}-s{seed}"

    cfg["name"]["value"] = name
    cfg["notes"]["value"] = (f"Revision R1 {run_id}: {model}, RGB+NIR+nDSM, {split} split, seed {seed}. "
                             f"Phase E recipe with batch size 4, max {MAX_EPOCHS} epochs, cosine T_max "
                             f"{MAX_EPOCHS - WARMUP_EPOCHS}. Generated by scripts/make_r1_configs.py.")
    hp = cfg["hyperparameters"]["value"]
    hp.update(batch_size=4, max_epochs=MAX_EPOCHS)
    hp.update(overrides.get("hyperparameters", {}))
    cosine = cfg["scheduler_hparams"]["value"]["schedulers"]["CosineAnnealingLR"]
    cosine["T_max"] = MAX_EPOCHS - WARMUP_EPOCHS
    if "model_factory" in overrides:
        cfg["model_factory"] = entry("Terratorch model factory to use", overrides["model_factory"])
    if overrides.get("model_factory") == "EncoderDecoderFactory":
        cfg["model_args"] = entry("Model arguments passed to the model factory", overrides["model_args"])
    elif "model_args" in overrides:
        cfg["model_args"]["value"].update(overrides["model_args"])

    cfg["seed"] = entry("Training seed (model init, sampling, augmentation); the grid split keeps seed 0", seed)
    # fixed budget: every run completes the warm-up + cosine schedule; the best val checkpoint is used
    cfg["early_stopping"] = entry("Stop when val/mIoU has not improved for `patience` epochs", False)
    if exclusion:
        cfg["exclusion"] = entry("Area kept out of train/val sampling", exclusion)
    cfg["wandb_tags"] = entry("W&B run tags", ["revision-r1", run_id, split])
    cfg["wandb_group"] = entry("W&B run group (model and split, so seed means never mix splits)", f"{model}-{split}")
    return name, cfg


def main():
    OUT.mkdir(exist_ok=True)
    written = []
    for run_id, (base_name, model, seeds, exclusion, overrides) in RUNS.items():
        for seed in seeds:
            name, cfg = make(run_id, base_name, model, seed, exclusion, overrides)
            path = OUT / f"config-{name}.yaml"
            path.write_text("# generated by scripts/make_r1_configs.py, edit the script instead\n"
                            + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
            written.append(f"{run_id:4s} {path.relative_to(ROOT)}")
    print("\n".join(written))


if __name__ == "__main__":
    main()
