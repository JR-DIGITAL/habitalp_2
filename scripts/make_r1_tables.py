    header = ("& \\multicolumn{4}{c}{2019/20 (cross-temporal)} & & \\multicolumn{4}{c}{2013 (in-domain)} \\\\\n"
              "\\cmidrule(lr){2-5}\\cmidrule(lr){7-10}\n"
              "Class group & E & F & $\\Delta$ & [95\\% CI] & & E & F & $\\Delta$ & [95\\% CI] \\\\")
    m = "Mean (6 models)"
    body = []
    for g, gname in groups:
        if g == "cc_merged":
            body.append("\\midrule")
        body.append(row([labels.get(g, gname)] + cells(m, "2020", g) + [""] + cells(m, "2013", g)))
    cap = ("Effect of the LiDAR nDSM on single-date segmentation, mean over the six models: macro IoU "
           "of RGB+NIR+nDSM (E) and RGB+NIR (F) and $\\Delta$ = E $-$ F by class group, at 0.2\\,m. "
           f"95\\% CI of $\\Delta$: {CI_TXT}, all models on the same resamples.")
