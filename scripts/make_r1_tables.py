    models = [m for m in ORDER if any(k[0] == m for k in d)]
    n_tiles = {y: next(r["n_tiles"] for r in rows_ if r["year"] == y) for y in ["2020", "2013"]}

    def cells(m, y, g):
        r = d.get((m, y, g))
        if r is None:
            return ["-"] * 4
        return [f(r["IoU_E"]), f(r["IoU_F"]), fs(r["dIoU"]), ci(r["dIoU_ci_low"], r["dIoU_ci_high"])]

    header = ("& \\multicolumn{4}{c}{2019/20 (cross-temporal)} & & \\multicolumn{4}{c}{2013 (in-domain)} \\\\\n"
              "\\cmidrule(lr){2-5}\\cmidrule(lr){7-10}\n"
              "Model & E & F & $\\Delta$ & [95\\% CI] & & E & F & $\\Delta$ & [95\\% CI] \\\\")
    body = []
    for i, (g, gname) in enumerate(B4_GROUPS):
        if i:
            body.append("\\midrule")
        body.append(f"\\multicolumn{{10}}{{l}}{{\\textit{{{gname}}}}} \\\\")
        for m in models:
            if m.startswith("Mean"):
                body.append("\\cmidrule(lr){1-10}")
            body.append(row([m] + cells(m, "2020", g) + [""] + cells(m, "2013", g)))
    cap = ("Effect of the LiDAR nDSM on single-date segmentation by class group: macro IoU of "
           "RGB+NIR+nDSM (E) and RGB+NIR (F) and the difference $\\Delta$ = E $-$ F, at 0.2\\,m. "
           "2019/20: cross-temporal test patches; 2013: in-domain test blocks. 95\\% CI of $\\Delta$: "
           f"{CI_TXT} (2019/20: {n_tiles['2020']} tiles; 2013: {n_tiles['2013']} tiles); the model mean "
           "uses the same resamples for all models. The CIs cover test-set sampling only, not "
           "training randomness (single runs).")
    notes = [("", "Canopy-cover classes: 8, 9, 11--18 (pole, mature and old forest split at 80\\% LiDAR "
                  "canopy cover). Other: classes 1--7, 10, 19--23. Merged: each CC$<$80 / CC$\\geq$80 "
                  "pair counted as one stage class.")]
