def b6() -> None:
    rows_ = read("b6_direct_cd_metrics.csv")
    b0 = read("b0_dwarffix_cd_metrics.csv")
    if rows_ is None:
        print("skip b6: b6_direct_cd_metrics.csv missing")
        return
    direct = defaultdict(dict)
    for r in rows_:
        direct[r["method"]]["bin" if r["task"] == "change-binary" else "mc"] = r
    labels = {"ChangeViT": ("ChangeViT", "binary"),
              "U-Net Change MiT-B2": ("U-Net, MiT-B2 encoder", "binary"),
              "U-Net Change EfficientNet-B4": ("U-Net, EfficientNet-B4 encoder", "9 classes")}

    def block(r, ci_lo="IoU_ci_low", ci_hi="IoU_ci_high", iou="IoU", f1="F1", ba="BA"):
        if r is None:
            return ["-"] * 4
        return [f(r[iou]), ci(r[ci_lo], r[ci_hi], signed=False), f(r[f1]), f(r[ba])]

    header = ("& & & \\multicolumn{4}{c}{Binary} & & \\multicolumn{4}{c}{Multi-class (9)} \\\\\n"
              "\\cmidrule(lr){4-7}\\cmidrule(lr){9-12}\n"
              "Method & Output & Input & IoU & [95\\% CI] & F1 & BA & & IoU & [95\\% CI] & F1 & BA \\\\")
    body = ["\\multicolumn{12}{l}{\\textit{Direct change detection (2025 models)}} \\\\"]
    for k, (lab, out) in labels.items():
        if k not in direct:
            continue
        mark = "\\tnote{a}" if "mc" in direct[k] else ""
        body.append(row([lab, out + mark, "RGB"] + block(direct[k].get("bin")) + [""] +
                        block(direct[k].get("mc"))))
    if b0 is not None:
        body += ["\\midrule",
                 "\\multicolumn{12}{l}{\\textit{Post-classification (this study, model output before "
                 "post-processing)}} \\\\"]
        sel = [("Clay v1.0", "E", "RGB+NIR+nDSM"), ("Clay v1.0", "F", "RGB+NIR"),
               ("U-Net", "E", "RGB+NIR+nDSM"), ("U-Net", "F", "RGB+NIR")]
        for m, ph, inp in sel:
            rr = {r["task"]: r for r in b0 if r["model"] == m and r["phase"] == ph
                  and r["postproc"] == "before"}
            kw = dict(iou="IoU_new", f1="F1_new", ba="BA_new", ci_lo="IoU_ci_low_new",
                      ci_hi="IoU_ci_high_new")
            body.append(row([NAMES[m], "9 classes", inp] + block(rr.get("change-binary"), **kw) + [""]
                            + block(rr.get("change-multiclass"), **kw)))
    agit = {labels[k][0]: direct[k] for k in labels if k in direct}
    ag = []
    for lab, dd in agit.items():
        for t, tn in [("bin", "binary"), ("mc", "multi-class")]:
            r = dd.get(t)
            if r and r.get("AGIT_IoU"):
                ag.append(f"{lab} {tn} {f(r['AGIT_IoU'], 2)}")
    cap = ("Direct change-detection maps scored with the evaluation of this study "
           "(2013$\\rightarrow$2019/20, reference change map at 0.2\\,m, same test area and metric code), "
           "next to the post-classification models. Macro IoU, macro F1 and balanced accuracy (BA); "
           f"95\\% CI of IoU: {CI_TXT_UNPAIRED} (88 tiles).")
    notes = [("a", "The 9-class map collapsed to change/no change for the binary columns."),
             ("", "Direct models were trained on RGB image pairs (2003 has no CIR) in 2025. "
                  "AGIT~v2 reported for them macro IoU " + "; ".join(ag) + ". These values differ "
                  "because this table uses the revised v4 reference change map and test area of all "
                  "other rows, whereas the AGIT~v2 direct rows reproduce only against an earlier "
                  "reference with a smaller share of changed pixels; its binary U-Net row also refers "
                  "to the nine-class model collapsed to change/no change.")]
    write("b6_direct_cd",
          table("tab:r1-b6_direct_cd", cap, "lll cccc c cccc", header, body, size="\\scriptsize",
                sep="3pt", wide=True, notes=notes),
          ["b6_direct_cd_metrics.csv", "b0_dwarffix_cd_metrics.csv"])


